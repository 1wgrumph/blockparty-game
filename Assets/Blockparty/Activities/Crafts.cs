// CRAFTS@1 (M5-OD-42): arts and crafts pieces that become furniture in the
// author's home. Plain C# 9, no engine dependency. A player request binds one
// craft kind to the CommandId of its own ACT-CREA-02 (Practice creative)
// carrier command; Track resolves that command to its current action id (SaveV1
// keeps CommandIds and renumbers actions on load) and drops the request once
// the carrier leaves the queue without completing (cancelled, replaced,
// abandoned). Only the committed completion of that exact action turns the
// kind into one persistent CraftPiece in the author's household home, and it
// charges the Make Wall Art material cost; without the money it makes no piece,
// as Make Wall Art does. Practice is the carrier because live residents hold no
// factual memory, so Make Wall Art (ACT-CREA-01) cannot complete in live play;
// Creative.Complete still grants the practice rewards. Completion is a
// post-executor boundary like Creative.Complete: one piece per
// ActionInstanceId, never applied twice. Pieces follow their author's
// household when it moves (FollowHouseholds).
// Every piece starts with the deterministic procedural image (CraftArt) and its
// disclosure, so it always exists; a generated Meta image may replace it later
// through SetGenerated, only within the M5-OD-46 cap (ImageProblem: a readable
// PNG of at most 4 MB and 1024x1024). The image prompt is built only from the
// craft kind, the author's trait words, the author's newest held memory and,
// for a portrait, the author's skin and hair tones.
// No static mutable state; all world writes go through audited WorldState
// methods with the caller StateWriter.
using System;
using System.Collections.Generic;
using Blockparty.Contracts;
using Blockparty.Simulation;

namespace Blockparty.Activities
{
    public enum CraftKind
    {
        Portrait = 0,
        Painting = 1,
        Poster = 2,
        Quilt = 3,
        StainedGlass = 4,
        Pottery = 5,
    }

    // Where a finished piece stands in the home.
    public enum CraftSlot
    {
        Wall = 0,
        Floor = 1,
        Shelf = 2,
    }

    public sealed class CraftPiece
    {
        public ObjectId Item { get; internal set; }
        public ResidentId Author { get; internal set; }
        public CraftKind Kind { get; internal set; }
        public HomeId Home { get; internal set; }
        public ActionInstanceId Action { get; internal set; }
        public string Prompt { get; internal set; }
        public string ImagePath { get; internal set; }
        public string ImageBase64 { get; internal set; }
        public string Disclosure { get; internal set; }
        public int Seed { get; internal set; }
        public int SkinTone { get; internal set; }
        public int HairColor { get; internal set; }
    }

    // Save bundle (crafts.json beside the SaveV1 save, see CraftsSave).
    public sealed class CraftsSnapshot
    {
        public sealed class PieceRow
        {
            public long Item;
            public long Author;
            public string Kind;
            public long Home;
            public long Action;
            public string Prompt;
            public string ImagePath;
            public string ImageBase64;
            public string Disclosure;
            public int Seed;
            public int SkinTone;
            public int HairColor;
        }

        public sealed class PendingRow
        {
            public long Resident;
            public string Kind;
            public long Command;
        }

        public readonly List<PieceRow> Pieces = new List<PieceRow>();
        public readonly List<PendingRow> Pending = new List<PendingRow>();
        public readonly List<long> Applied = new List<long>();
    }

    public sealed class Crafts
    {
        public const string CarrierActivity = "ACT-CREA-02";
        public const string ProceduralPath = "procedural";
        public const string GeneratedPath = "generated";
        public const int MaxPending = 8;
        // Same as Creative's Make Wall Art material cost (Creative.MaterialCost, ACT-CREA-01).
        public const long MaterialCost = 10L;
        // M5-OD-46: generated images over 4 MB or 1024x1024 use the procedural picture.
        public const int MaxImageBytes = 4 * 1024 * 1024;
        public const int MaxImageSide = 1024;
        public const string GeneratedDisclosure =
            "Generated by Meta image generation (muse-image-1.0) from the prompt below.";
        private const string ProceduralDisclosure =
            "Procedural pattern painted in-game; image generation was not used";

        public static readonly string[] KindNames =
        {
            "Portrait", "Painting", "Poster", "Woven quilt rug", "Stained glass", "Clay pottery",
        };

        // What the finished piece becomes, for the menu tooltip.
        public static readonly string[] KindHints =
        {
            "A framed self-portrait for a wall",
            "A framed landscape or still-life for a wall",
            "A bold poster for a wall",
            "A patchwork rug for the floor",
            "A glowing window panel for a wall",
            "A hand-thrown vase glazed with the artwork, for a shelf",
        };

        private static readonly string[] SkinWords =
        {
            "very light", "light", "medium", "tan", "brown", "deep brown",
        };

        private static readonly string[] HairWords =
        {
            "black", "dark brown", "auburn", "golden", "blonde", "grey",
        };

        // One queued craft: its kind, the carrier command and that command's current action.
        private sealed class CraftRequest
        {
            public ResidentId Resident;
            public CraftKind Kind;
            public CommandId Command;
            public ActionInstanceId Action;
        }

        private readonly WorldState world;
        private readonly List<CraftPiece> pieces = new List<CraftPiece>();
        private readonly List<CraftRequest> pending = new List<CraftRequest>();
        private readonly HashSet<ActionInstanceId> applied = new HashSet<ActionInstanceId>();

        public Crafts(WorldState world)
        {
            if (world == null)
            {
                throw new ArgumentNullException("world");
            }
            this.world = world;
        }

        public IReadOnlyList<CraftPiece> Pieces
        {
            get { return pieces.AsReadOnly(); }
        }

        // Why the last bound completion made no piece (null when it made one).
        public string LastRefusal { get; private set; }

        public static CraftSlot SlotOf(CraftKind kind)
        {
            if (kind == CraftKind.Quilt) return CraftSlot.Floor;
            if (kind == CraftKind.Pottery) return CraftSlot.Shelf;
            return CraftSlot.Wall;
        }

        public CraftPiece Find(ObjectId item)
        {
            for (int i = 0; i < pieces.Count; i++)
            {
                if (pieces[i].Item == item) return pieces[i];
            }
            return null;
        }

        public int PendingCount(ResidentId resident)
        {
            int count = 0;
            foreach (CraftRequest request in pending) if (request.Resident == resident) count++;
            return count;
        }

        // Queues one craft kind for a living resident with a household home, bound
        // to the carrier command the caller submits with this CommandId.
        public bool Request(ResidentId resident, CraftKind kind, CommandId command)
        {
            if (!IsKind(kind) || (long)command <= 0L || PendingCount(resident) >= MaxPending) return false;
            ResidentRecord record;
            HomeId home;
            if (!world.TryGetResident(resident, out record) || !record.IsAlive || !TryHome(record, out home))
            {
                return false;
            }
            foreach (CraftRequest other in pending) if (other.Command == command) return false;
            CraftRequest request = new CraftRequest();
            request.Resident = resident;
            request.Kind = kind;
            request.Command = command;
            pending.Add(request);
            return true;
        }

        // Drops the request of a carrier command the arbitrator refused.
        public void CancelRequest(CommandId command)
        {
            pending.RemoveAll(r => r.Command == command);
        }

        // Binds each request to its carrier command's current action id and drops
        // the requests whose carrier left the queue without a completed piece
        // (cancelled, replaced, abandoned, or not resumed by a load). Call it after
        // submitting a carrier, after a load and after each frame's completions.
        public int Track(CommandArbitrator arbitrator)
        {
            if (arbitrator == null) throw new ArgumentNullException("arbitrator");
            return pending.RemoveAll(request =>
            {
                ActionEntry entry = CarrierEntry(arbitrator, request);
                if (entry == null) return true;
                request.Action = entry.Action;
                return false;
            });
        }

        // Moves every piece whose author's household now lives elsewhere into that
        // home. Returns true when a piece moved.
        public bool FollowHouseholds()
        {
            bool moved = false;
            foreach (CraftPiece piece in pieces)
            {
                ResidentRecord author;
                HomeId home;
                if (world.TryGetResident(piece.Author, out author) && TryHome(author, out home) && home != piece.Home)
                {
                    piece.Home = home;
                    moved = true;
                }
            }
            return moved;
        }

        // The committed completion of a request's own carrier action becomes one
        // piece and charges MaterialCost. Returns null for any other action, an
        // already applied id, or a carrier whose author cannot pay (LastRefusal).
        public CraftPiece Complete(StateWriter writer, ActionInstanceId action, ActivityId activity,
            ResidentId author, AppearanceStore appearances)
        {
            CheckWriter(writer);
            LastRefusal = null;
            if (applied.Contains(action)) return null;
            if (!string.Equals(activity.Code ?? string.Empty, CarrierActivity, StringComparison.Ordinal))
            {
                return null;
            }
            int index = pending.FindIndex(r => r.Action == action && r.Resident == author && (long)action > 0L);
            if (index < 0) return null;
            CraftKind kind = pending[index].Kind;
            pending.RemoveAt(index);
            ResidentRecord record;
            HomeId home;
            if (!CommittedFor(action, author) || !world.TryGetResident(author, out record) || !record.IsAlive
                || !TryHome(record, out home))
            {
                return null;
            }
            applied.Add(action);
            if (record.Money < MaterialCost)
            {
                LastRefusal = "not enough money for the materials (" + MaterialCost.ToString() + " needed)";
                return null;
            }
            world.SetMoney(writer, author, record.Money - MaterialCost);
            AppearanceRecord look = null;
            if (appearances != null) appearances.TryGet(author, out look);
            CraftPiece piece = new CraftPiece();
            piece.Item = world.AllocateObject(writer);
            piece.Author = author;
            piece.Kind = kind;
            piece.Home = home;
            piece.Action = action;
            piece.SkinTone = look == null ? 2 : Clamp(look.SkinTone, 0, SkinWords.Length - 1);
            piece.HairColor = look == null ? 1 : Clamp(look.HairColor, 0, HairWords.Length - 1);
            piece.Seed = SeedOf((long)piece.Item, (long)author, kind);
            piece.Prompt = BuildPrompt(kind, record, NewestMemoryDetail(record), piece.SkinTone, piece.HairColor);
            piece.ImagePath = ProceduralPath;
            piece.ImageBase64 = string.Empty;
            piece.Disclosure = ProceduralDisclosure + ".";
            pieces.Add(piece);
            return piece;
        }

        // A generated PNG within the image cap replaces the procedural image once.
        // The caller decodes it first; an image it cannot decode stays procedural.
        public bool SetGenerated(ObjectId item, string pngBase64)
        {
            CraftPiece piece = Find(item);
            if (piece == null || ImageProblem(pngBase64) != null) return false;
            piece.ImagePath = GeneratedPath;
            piece.ImageBase64 = pngBase64;
            piece.Disclosure = GeneratedDisclosure;
            return true;
        }

        // Keeps the procedural image and records why generation was not used.
        public bool SetProcedural(ObjectId item, string reason)
        {
            CraftPiece piece = Find(item);
            if (piece == null || piece.ImagePath == GeneratedPath) return false;
            piece.Disclosure = ProceduralDisclosure
                + (string.IsNullOrEmpty(reason) ? "." : " (" + reason + ").");
            return true;
        }

        // The prompt: craft kind, trait words, the newest held memory and, for a
        // portrait, skin and hair tones. No name or other resident data.
        public static string BuildPrompt(CraftKind kind, ResidentRecord author, string memory,
            int skinTone, int hairColor)
        {
            if (author == null) throw new ArgumentNullException("author");
            string subject;
            switch (kind)
            {
                case CraftKind.Portrait:
                    subject = "A framed head-and-shoulders self-portrait painting of a neighbour with "
                        + SkinWords[Clamp(skinTone, 0, SkinWords.Length - 1)] + " skin and "
                        + HairWords[Clamp(hairColor, 0, HairWords.Length - 1)] + " hair, smiling";
                    break;
                case CraftKind.Painting:
                    subject = author.GetTrait(TraitAxis.Active) >= 0
                        ? "A framed landscape painting of a friendly neighbourhood with rolling hills, little houses and a big sky"
                        : "A framed still-life painting of fruit, a teapot and a flower vase on a wooden table";
                    break;
                case CraftKind.Poster:
                    subject = "A bold graphic poster for a neighbourhood block party, simple shapes";
                    break;
                case CraftKind.Quilt:
                    subject = "A woven patchwork quilt rug seen straight from above, geometric patches and stitched borders";
                    break;
                case CraftKind.StainedGlass:
                    subject = "A stained-glass window panel with jewel-coloured glass and bold dark lead lines";
                    break;
                default:
                    subject = "A seamless hand-painted glaze pattern for a clay pottery vase, brushstroke bands and waves";
                    break;
            }
            string traits = TraitWords(author);
            string text = subject + ". Made by " + ("aeiou".IndexOf(traits[0]) >= 0 ? "an " : "a ") + traits + " neighbour";
            if (!string.IsNullOrEmpty(memory))
            {
                text += ", inspired by the memory: " + memory.Trim();
            }
            return text + ". Cosy hand-made look, warm storybook palette of ivory, teal, rust, denim and gold, flat front view, no text.";
        }

        public CraftsSnapshot Export()
        {
            CraftsSnapshot snapshot = new CraftsSnapshot();
            List<CraftPiece> sorted = new List<CraftPiece>(pieces);
            sorted.Sort(delegate (CraftPiece a, CraftPiece b) { return ((long)a.Item).CompareTo((long)b.Item); });
            foreach (CraftPiece piece in sorted)
            {
                CraftsSnapshot.PieceRow row = new CraftsSnapshot.PieceRow();
                row.Item = (long)piece.Item;
                row.Author = (long)piece.Author;
                row.Kind = piece.Kind.ToString();
                row.Home = (long)piece.Home;
                row.Action = (long)piece.Action;
                row.Prompt = piece.Prompt;
                row.ImagePath = piece.ImagePath;
                row.ImageBase64 = piece.ImageBase64;
                row.Disclosure = piece.Disclosure;
                row.Seed = piece.Seed;
                row.SkinTone = piece.SkinTone;
                row.HairColor = piece.HairColor;
                snapshot.Pieces.Add(row);
            }
            foreach (CraftRequest request in pending)
            {
                CraftsSnapshot.PendingRow row = new CraftsSnapshot.PendingRow();
                row.Resident = (long)request.Resident;
                row.Kind = request.Kind.ToString();
                row.Command = (long)request.Command;
                snapshot.Pending.Add(row);
            }
            List<long> ids = new List<long>();
            foreach (ActionInstanceId id in applied) ids.Add((long)id);
            ids.Sort();
            snapshot.Applied.AddRange(ids);
            return snapshot;
        }

        // Binds a saved bundle to the loaded world. Any row that contradicts the
        // world refuses the whole bundle and leaves the current state untouched.
        public void Import(StateWriter writer, CraftsSnapshot snapshot)
        {
            CheckWriter(writer);
            if (snapshot == null) throw new ArgumentNullException("snapshot");
            List<CraftPiece> nextPieces = new List<CraftPiece>();
            HashSet<long> items = new HashSet<long>();
            foreach (CraftsSnapshot.PieceRow row in snapshot.Pieces)
            {
                if (row == null || row.Prompt == null || row.ImagePath == null
                    || row.ImageBase64 == null || row.Disclosure == null)
                {
                    throw new ArgumentException("Null craft piece row", "snapshot");
                }
                CraftKind kind;
                if (!TryKind(row.Kind, out kind))
                {
                    throw new ArgumentException("Unknown craft kind " + row.Kind, "snapshot");
                }
                if (row.Item <= 0L || row.Item >= world.NextObjectId || !items.Add(row.Item))
                {
                    throw new ArgumentException("Craft item " + row.Item.ToString()
                        + " is duplicated or beyond the saved id high-water mark", "snapshot");
                }
                ResidentRecord author;
                HomeRecord home;
                if (!world.TryGetResident((ResidentId)row.Author, out author)
                    || !world.TryGetHome((HomeId)row.Home, out home))
                {
                    throw new ArgumentException("Craft item " + row.Item.ToString()
                        + " names an unknown author or home", "snapshot");
                }
                if (row.Action <= 0L || row.Action >= world.NextActionId)
                {
                    throw new ArgumentException("Craft item " + row.Item.ToString()
                        + " names an unknown action", "snapshot");
                }
                bool generated = string.Equals(row.ImagePath, GeneratedPath, StringComparison.Ordinal);
                if (!generated && !string.Equals(row.ImagePath, ProceduralPath, StringComparison.Ordinal))
                {
                    throw new ArgumentException("Craft item " + row.Item.ToString() + " has an unknown image path", "snapshot");
                }
                if (generated ? ImageProblem(row.ImageBase64) != null : row.ImageBase64.Length != 0)
                {
                    throw new ArgumentException("Craft item " + row.Item.ToString() + " image does not match its path", "snapshot");
                }
                CraftPiece piece = new CraftPiece();
                piece.Item = (ObjectId)row.Item;
                piece.Author = author.Id;
                piece.Kind = kind;
                piece.Home = home.Id;
                piece.Action = (ActionInstanceId)row.Action;
                piece.Prompt = row.Prompt;
                piece.ImagePath = row.ImagePath;
                piece.ImageBase64 = row.ImageBase64;
                piece.Disclosure = row.Disclosure;
                piece.Seed = row.Seed;
                piece.SkinTone = Clamp(row.SkinTone, 0, SkinWords.Length - 1);
                piece.HairColor = Clamp(row.HairColor, 0, HairWords.Length - 1);
                nextPieces.Add(piece);
            }
            List<CraftRequest> nextPending = new List<CraftRequest>();
            HashSet<long> commands = new HashSet<long>();
            foreach (CraftsSnapshot.PendingRow row in snapshot.Pending)
            {
                CraftKind kind;
                ResidentRecord resident;
                if (row == null || !TryKind(row.Kind, out kind) || row.Command <= 0L || !commands.Add(row.Command)
                    || !world.TryGetResident((ResidentId)row.Resident, out resident))
                {
                    throw new ArgumentException("Invalid pending craft row", "snapshot");
                }
                if (nextPending.FindAll(r => r.Resident == resident.Id).Count >= MaxPending)
                {
                    throw new ArgumentException("Too many pending crafts for one resident", "snapshot");
                }
                CraftRequest request = new CraftRequest();
                request.Resident = resident.Id;
                request.Kind = kind;
                request.Command = (CommandId)row.Command;
                nextPending.Add(request);
            }
            HashSet<ActionInstanceId> nextApplied = new HashSet<ActionInstanceId>();
            foreach (long id in snapshot.Applied)
            {
                if (id <= 0L || id >= world.NextActionId || !nextApplied.Add((ActionInstanceId)id))
                {
                    throw new ArgumentException("Invalid applied craft action " + id.ToString(), "snapshot");
                }
            }
            foreach (CraftPiece piece in nextPieces)
            {
                if (!nextApplied.Contains(piece.Action))
                {
                    throw new ArgumentException("Craft item " + ((long)piece.Item).ToString()
                        + " action is not recorded as applied", "snapshot");
                }
            }
            pieces.Clear();
            pieces.AddRange(nextPieces);
            pending.Clear();
            pending.AddRange(nextPending);
            applied.Clear();
            foreach (ActionInstanceId id in nextApplied) applied.Add(id);
            FollowHouseholds();
        }

        public bool HasSaveState()
        {
            return pieces.Count != 0 || pending.Count != 0 || applied.Count != 0;
        }

        public static bool TryKind(string name, out CraftKind kind)
        {
            kind = CraftKind.Portrait;
            if (string.IsNullOrEmpty(name)) return false;
            foreach (CraftKind candidate in (CraftKind[])Enum.GetValues(typeof(CraftKind)))
            {
                if (string.Equals(candidate.ToString(), name, StringComparison.Ordinal))
                {
                    kind = candidate;
                    return true;
                }
            }
            return false;
        }

        // Null when a generated image may be used; otherwise the player-facing
        // reason. The length is checked before any decoding allocates; the PNG
        // header must hold a first IHDR chunk with non-zero dimensions within the cap.
        public static string ImageProblem(string base64)
        {
            const string Unreadable = "the generated image is not a readable PNG";
            const string TooBig = "the generated image is over 4 MB";
            if (string.IsNullOrEmpty(base64)) return Unreadable;
            if (base64.Length > (MaxImageBytes + 2) / 3 * 4) return TooBig;
            byte[] b;
            try { b = Convert.FromBase64String(base64); }
            catch (FormatException) { return Unreadable; }
            if (b.Length > MaxImageBytes) return TooBig;
            byte[] header = { 137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13, 73, 72, 68, 82 };
            if (b.Length < 33) return Unreadable;
            for (int i = 0; i < header.Length; i++) if (b[i] != header[i]) return Unreadable;
            long width = ((long)b[16] << 24) | ((long)b[17] << 16) | ((long)b[18] << 8) | b[19];
            long height = ((long)b[20] << 24) | ((long)b[21] << 16) | ((long)b[22] << 8) | b[23];
            if (width == 0L || height == 0L) return Unreadable;
            if (width > MaxImageSide || height > MaxImageSide) return "the generated image is over 1024x1024";
            return null;
        }

        private bool TryHome(ResidentRecord record, out HomeId home)
        {
            home = default(HomeId);
            HouseholdRecord household;
            if (!world.TryGetHousehold(record.Household, out household)) return false;
            HomeRecord row;
            if (!world.TryGetHome(household.Home, out row)) return false;
            home = row.Id;
            return true;
        }

        // Same pick as AlphaDirector.LiveTick's Wall Art memory: the newest held memory.
        private string NewestMemoryDetail(ResidentRecord record)
        {
            if (record.Memories.Count == 0) return string.Empty;
            EventId newest = record.Memories[record.Memories.Count - 1].Event;
            IReadOnlyList<WorldEvent> events = world.Events;
            for (int i = 0; i < events.Count; i++)
            {
                if (events[i].Event == newest) return events[i].Detail ?? string.Empty;
            }
            return string.Empty;
        }

        // The two strongest positive traits as plain words.
        private static string TraitWords(ResidentRecord record)
        {
            string[] words = { "friendly", "driven", "energetic", "imaginative", "tidy", "playful" };
            int first = -1, second = -1;
            for (int i = 0; i < words.Length; i++)
            {
                int value = record.GetTrait((TraitAxis)i);
                if (value <= 0) continue;
                if (first < 0 || value > record.GetTrait((TraitAxis)first)) { second = first; first = i; }
                else if (second < 0 || value > record.GetTrait((TraitAxis)second)) second = i;
            }
            if (first < 0) return "quiet, thoughtful";
            return second < 0 ? words[first] : words[first] + ", " + words[second];
        }

        private static ActionEntry CarrierEntry(CommandArbitrator arbitrator, CraftRequest request)
        {
            ActionEntry current = arbitrator.GetCurrent(request.Resident);
            if (current != null && current.Command == request.Command) return current;
            foreach (ActionEntry entry in arbitrator.GetPending(request.Resident))
            {
                if (entry.Command == request.Command) return entry;
            }
            return null;
        }

        private bool CommittedFor(ActionInstanceId action, ResidentId author)
        {
            IReadOnlyList<EffectLedgerEntry> ledger = world.EffectLedger;
            for (int i = 0; i < ledger.Count; i++)
            {
                EffectLedgerEntry entry = ledger[i];
                if (entry.Action != action) continue;
                return entry.State == LedgerState.Committed
                    && entry.Recipient.First == author
                    && string.Equals(entry.EffectKind, CarrierActivity, StringComparison.Ordinal);
            }
            return false;
        }

        private static int SeedOf(long item, long author, CraftKind kind)
        {
            unchecked
            {
                long hash = item * 2654435761L ^ (author * 40503L) ^ ((long)kind * 97L + 13L);
                return (int)(hash ^ (hash >> 32)) & 0x7fffffff;
            }
        }

        private static bool IsKind(CraftKind kind)
        {
            return kind >= CraftKind.Portrait && kind <= CraftKind.Pottery;
        }

        private static int Clamp(int value, int min, int max)
        {
            return value < min ? min : value > max ? max : value;
        }

        private static void CheckWriter(StateWriter writer)
        {
            if (writer != StateWriter.SimCore && writer != StateWriter.CommandArbitrator
                && writer != StateWriter.ActivityExecutor)
            {
                throw new ArgumentException("Unknown state writer", "writer");
            }
        }
    }
