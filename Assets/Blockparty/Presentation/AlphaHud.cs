            wrap.wordWrap = true;
            GUI.Label(new Rect(card.x + U(30), y, w - U(60), U(36)), f.ContinueNote, wrap);
            wrap.wordWrap = false;
        }
        string hint = Key(f, "SelectNext") + "/" + Key(f, "SelectPrevious") + " choose · "
