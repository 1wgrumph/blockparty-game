    void Setup(Frame f)
    {
        if (atlas == null) atlas = Resources.Load<Texture2D>("HudIcons");
        if (font == null) font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        float t = f.Access.Settings.TextScale;
        float u = Mathf.Clamp(Screen.height / 1080f, 0.8f, 2f);
        float g = Mathf.Lerp(1f, t, 0.6f);
        // The bottom row (strip + tray) must fit the width; shrink uniformly if not.
        float row = 26f + StripWidth(f) + 16f + TrayWidth() + 26f;
        float fit = Mathf.Clamp(Screen.width / (row * u * g), 0.7f, 1f);
        k = u * g * fit;
        kf = u * t * fit;
        if (label == null)
        {
            label = new GUIStyle { font = font, clipping = TextClipping.Clip, wordWrap = false, richText = false };
            skin = ScriptableObject.CreateInstance<GUISkin>();
            skin.hideFlags = HideFlags.HideAndDontSave;
            skin.font = font;
        }
        int key = Mathf.RoundToInt(k * 100f);
        if (key != texKey) { texKey = key; BuildTextures(); LogLayout(); }
        if (Screen.width != lastWidth || Screen.height != lastHeight)
        {
            lastWidth = Screen.width;
            lastHeight = Screen.height;
            Rect outing = TileRect(f, 10);
            // The capture driver clicks this rectangle; no other consumer.
            Debug.Log("hud tray-outing center=" + outing.center.x.ToString("F0", CultureInfo.InvariantCulture)
                + "," + outing.center.y.ToString("F0", CultureInfo.InvariantCulture));
            Rect social = TileRect(f, 3);   // SOCIAL-LIVE capture driver only
            Debug.Log("hud tray-social center=" + social.center.x.ToString("F0", CultureInfo.InvariantCulture)
                + "," + social.center.y.ToString("F0", CultureInfo.InvariantCulture));

        }
    }

