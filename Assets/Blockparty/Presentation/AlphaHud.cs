    void SaveKey(bool clear)
    {
        bool ok = false;
        try
        {
            var settings = new KeySettings();
            if (!clear) settings.SetKey(keyEntry);
            settings.Save(KeySettings.DefaultPath());
            ok = true;
            keyNote = clear ? "Key removed" : "Key saved";
        }
        catch (ArgumentException) { keyNote = "Paste a key first (no spaces or line breaks inside)"; }
        catch (Exception e) { keyNote = "Could not save: " + e.GetType().Name; }   // never e.Message
        keyEntry = string.Empty;
        RefreshKeyStatus();
        Debug.Log("ALPHA key " + (clear ? "clear" : "save") + " ok=" + ok + " status=\"" + KeyStatus() + "\"");
    }

