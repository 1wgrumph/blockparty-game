    // ROSTER-STRIP (owner playtest 2026-11-04): every resident gets a circle. The strip shows
    // PageSize of them (the selected one and the newest arrivals and births always among them);
    // the chevron opens a panel above it with every resident, passed ones dimmed at the end.
    bool rosterOpen;
    WorldState seenWorld;
    readonly HashSet<ResidentId> seen = new HashSet<ResidentId>();
    readonly List<ResidentId> newcomers = new List<ResidentId>();   // newest first

    List<ResidentRecord> Passed(Frame f)
    {
        var passed = new List<ResidentRecord>();
        foreach (ResidentId id in f.Residents)
        {
            ResidentRecord r;
            if (f.World.TryGetResident(id, out r) && !r.IsAlive) passed.Add(r);
        }
        return passed;
    }

    // Residents not seen before in this world are newcomers (a load or new game starts a fresh set).
    void TrackNewcomers(Frame f, List<ResidentRecord> roster)
    {
        if (!ReferenceEquals(seenWorld, f.World))
        {
            seenWorld = f.World;
            seen.Clear();
            newcomers.Clear();
            foreach (ResidentId id in f.Residents) seen.Add(id);
            return;
        }
        foreach (ResidentRecord r in roster)
        {
            if (!seen.Add(r.Id)) continue;
            newcomers.Insert(0, r.Id);
            Debug.Log("ALPHA roster added resident=" + (long)r.Id + " name=" + r.DisplayName + " stage=" + r.Stage + " alive=" + roster.Count);
        }
    }

    // The strip's circles in roster order: all of them when they fit, otherwise the selected
    // resident, then the newest arrivals, then the rest in roster order.
    List<ResidentRecord> StripShown(List<ResidentRecord> roster, ResidentRecord resident)
    {
        if (roster.Count <= PageSize) return roster;
        var pick = new HashSet<ResidentId>();
        if (resident != null) pick.Add(resident.Id);
        foreach (ResidentId id in newcomers)
        {
            if (pick.Count >= PageSize) break;
            if (roster.Exists(r => r.Id.Equals(id))) pick.Add(id);
        }
        foreach (ResidentRecord r in roster)
        {
            if (pick.Count >= PageSize) break;
            pick.Add(r.Id);
        }
        return roster.FindAll(r => pick.Contains(r.Id));
    }

    // Sized for a full strip so the tray does not shift as residents come and go.
    float StripWidth(Frame f)
    {
        int households;
        int n = Roster(f, out households).Count;
        int shown = Mathf.Clamp(n, 1, PageSize);
        return 20f + shown * 60f + (shown - 1) * 8f + Mathf.Min(households - 1, shown - 1) * 8f + 20f
            + (n > PageSize || Passed(f).Count > 0 ? 42f : 0f);
    }

