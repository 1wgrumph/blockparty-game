        if (fraction <= 0f) return;
        float w = Mathf.Max(track.height, track.width * fraction);
        Panel(fill, new Rect(track.x, track.y, w, track.height), false);
    }

    static float LowestNeed(ResidentRecord r)
    {
        float low = float.MaxValue;
