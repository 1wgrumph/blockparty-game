    static string Countdown(long seconds)
    {
        long h = seconds / 3600L, m = seconds % 3600L / 60L;
        return h > 0 ? h.ToString(CultureInfo.InvariantCulture) + "h " + m.ToString("00", CultureInfo.InvariantCulture) + "m"
                     : m.ToString(CultureInfo.InvariantCulture) + "m";
    }

    static string Clock12(long gameSeconds)
    {
        long ofDay = gameSeconds % Clockwork.GameSecondsPerGameDay;
        long hour = ofDay / 3600L, minute = ofDay % 3600L / 60L;
        return ((hour + 11L) % 12L + 1L).ToString(CultureInfo.InvariantCulture) + ":" + minute.ToString("00", CultureInfo.InvariantCulture)
            + (hour < 12L ? " AM" : " PM");
    }

