    public void Draw(Frame f)
    {
        Event e = Event.current;
        Setup(f);
        if (portraits == null) portraits = new GameObject("AlphaPortraits").AddComponent<AlphaPortraits>();
        portraits.Frame = f;
        GUISkin previous = GUI.skin;
        GUI.skin = skin;
        tooltip = null;
        if (e.type == EventType.Repaint) drawn.Clear();
        if (f.Voice != null && f.Voice.PageOpen)
        {
            DrawVoicePage(f);   // VOICE-LIVE: the Voice page is modal
            DrawTooltip();
            if (e.type == EventType.Repaint) { blockers.Clear(); blockers.AddRange(drawn); }
            GUI.skin = previous;
            return;
        }
        if (f.Controls != null && f.Controls.Open)
        {
            DrawControls(f);   // CONTROLS-LOGO: the rebind page is modal
            DrawTooltip();
            if (e.type == EventType.Repaint) { blockers.Clear(); blockers.AddRange(drawn); }
            GUI.skin = previous;
            return;
        }
        if (!f.SettingsOpen) CloseKeyPage();   // closing Settings also drops any unsaved entry
        if (f.TitleOpen)
        {
            DrawTitle(f);
            if (f.SettingsOpen) DrawSettings(f);
            if (f.Failed) DrawFailure(f);
            if (e.type == EventType.Repaint) { blockers.Clear(); blockers.AddRange(drawn); }
            GUI.skin = previous;
            return;
        }
        if (f.SettingsOpen) { historyOpen = false; rosterOpen = false; }
        ResidentId? selected = f.Navigation.SelectedResident;
        ResidentRecord resident = null;
        if (selected.HasValue && (!f.World.TryGetResident(selected.Value, out resident) || !resident.IsAlive)) resident = null;

        snapshot = resident != null ? f.Hud.Snapshot(Screen.width, Screen.height) : null;
        DrawWorldTag(f, resident);
        DrawHelp(f);
        float topBottom = DrawTopBar(f, resident);
        DrawCorner(f);
        DrawToast(f, DrawPaused(f, topBottom));
        float rowTop = DrawBottomRow(f, resident, out float trayRight);
        if (resident != null && !rosterOpen) DrawNeeds(f, resident, rowTop);
        DrawVoiceIndicator(f, rowTop);
        // The card joins the bottom row when at least 320 units remain beside the tray.
        float room = Screen.width - U(26) - trayRight - U(16);
        bool inRow = room >= U(320);
        cardWidth = inRow ? Mathf.Min(U(360), room) : U(360);
        float ctxBottom = inRow ? Screen.height - U(26) : rowTop - U(16);
        // Settings overlaps the contextual card and IMGUI gives clicks to the earlier control,
        // so the card is hidden (its open state kept) while Settings is open.
        if (!f.SettingsOpen && !historyOpen && !rosterOpen)
        {
            if (f.PlanOpen && f.Live != null) DrawPlanCard(f, ctxBottom, topBottom);
            else if (f.Input.MenuOpen) DrawActionCard(f, resident, ctxBottom, topBottom);
            else if (outingOpen && f.Trail != null && f.Trail.Layout != null) DrawOutingCard(f, ctxBottom, topBottom);
        }
        DrawLook(f);   // SAM-LOOK
        if (f.SettingsOpen) DrawSettings(f);
        if (historyOpen) DrawHistory(f);
        if (f.Failed) DrawFailure(f);
        DrawTooltip();
        if (e.type == EventType.Repaint) { blockers.Clear(); blockers.AddRange(drawn); }
        GUI.skin = previous;
    }

