    // Rounded box as a 9-slice: radius, vertical fill gradient, inner stroke,
    // inset band (positive = bottom, negative = top) and an offset soft shadow.
    void AddNine(string name, float radius, Color fillTop, Color fillBottom, float border, Color borderColor,
        float inset, Color insetColor, float drop, float blur, Color shadow, float fixedHeight = 0f)
    {
        float r = Mathf.Max(1f, radius * k), b = border * k, ins = inset * k, dr = drop * k, bl = Mathf.Max(0.75f, blur * k);
        int pad = shadow.a > 0f ? Mathf.CeilToInt(dr + bl + 1f) : 0;
        int bodyH = fixedHeight > 0f ? Mathf.Max(2, Mathf.RoundToInt(fixedHeight * k)) : Mathf.CeilToInt(2f * r) + 2;
        if (fixedHeight > 0f) r = Mathf.Min(r, bodyH / 2f);
        int bodyW = Mathf.CeilToInt(2f * r) + 2;
        int w = bodyW + 2 * pad, h = bodyH + 2 * pad;
        Texture2D tex = new Texture2D(w, h, TextureFormat.RGBA32, false)
        { wrapMode = TextureWrapMode.Clamp, filterMode = FilterMode.Bilinear, hideFlags = HideFlags.HideAndDontSave };
        Color[] px = new Color[w * h];
        Vector2 half = new Vector2(bodyW / 2f, bodyH / 2f), c = new Vector2(w / 2f, h / 2f);
        for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
            {
                Vector2 p = new Vector2(x + 0.5f, y + 0.5f);   // y down
                float d = Box(p - c, half, r);
                Color o = Color.clear;
                if (shadow.a > 0f)
                {
                    float ds = Box(p - c - new Vector2(0f, dr), half, r);
                    float sa = shadow.a * (1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(-bl, bl, ds)));
                    o = new Color(shadow.r, shadow.g, shadow.b, sa);
                }
                float cov = Mathf.Clamp01(0.5f - d);
                if (cov > 0f)
                {
                    float ty = Mathf.Clamp01((p.y - pad) / bodyH);
                    Color fill = Color.Lerp(fillTop, fillBottom, ty);
                    if (ins != 0f)
                    {
                        float band = Mathf.Clamp01(0.5f + Box(p - c + new Vector2(0f, ins), half, r));
                        fill = Color.Lerp(fill, insetColor, band * insetColor.a);
                    }
                    if (b > 0f)
                    {
                        float stroke = Mathf.Clamp01(d + b + 0.5f);
                        fill = Over(fill, new Color(borderColor.r, borderColor.g, borderColor.b, borderColor.a * stroke));
                    }
                    o = Over(o, new Color(fill.r, fill.g, fill.b, fill.a * cov));
                }
                px[(h - 1 - y) * w + x] = o;
            }
        tex.SetPixels(px);
        tex.Apply(false, true);
        owned.Add(tex);
        int edge = pad + Mathf.CeilToInt(r);
        int top = fixedHeight > 0f ? pad + bodyH / 2 : edge;
        int bottom = fixedHeight > 0f ? h - top : edge;
        GUIStyle style = new GUIStyle { border = new RectOffset(edge, edge, top, bottom) };
        style.normal.background = tex;
        nines[name] = new Nine { Style = style, Pad = pad };
    }

    static float Box(Vector2 p, Vector2 half, float r)
    {
        Vector2 q = new Vector2(Mathf.Abs(p.x), Mathf.Abs(p.y)) - half + new Vector2(r, r);
        return new Vector2(Mathf.Max(q.x, 0f), Mathf.Max(q.y, 0f)).magnitude + Mathf.Min(Mathf.Max(q.x, q.y), 0f) - r;
    }

    static Color Over(Color under, Color over)
    {
        float a = over.a + under.a * (1f - over.a);
        if (a <= 0f) return Color.clear;
        Color rgb = (over * over.a + under * under.a * (1f - over.a)) / a;
        rgb.a = a;
        return rgb;
    }

    static Color Hex(int rgb) { return new Color(((rgb >> 16) & 255) / 255f, ((rgb >> 8) & 255) / 255f, (rgb & 255) / 255f, 1f); }
    static Color A(Color c, float a) { c.a = a; return c; }

