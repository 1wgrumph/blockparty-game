    const int PageSize = 8;

    // Alive residents grouped by household (first-appearance order), then by roster order.
    List<ResidentRecord> Roster(Frame f, out int households)
    {
        var order = new List<HouseholdId>();
        var alive = new List<ResidentRecord>();
        foreach (ResidentId id in f.Residents)
        {
            ResidentRecord r;
            if (!f.World.TryGetResident(id, out r) || !r.IsAlive) continue;
            alive.Add(r);
            if (!order.Contains(r.Household)) order.Add(r.Household);
        }
        var grouped = new List<ResidentRecord>(alive.Count);
        foreach (HouseholdId h in order)
            foreach (ResidentRecord r in alive) if (r.Household.Equals(h)) grouped.Add(r);
        households = order.Count;
        return grouped;
    }

    bool helpCollapsedOnce;
