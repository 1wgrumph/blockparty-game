            GUI.DrawTexture(new Rect(0, 0, Screen.width, Screen.height), Texture2D.whiteTexture, ScaleMode.StretchToFill, true, 0, A(Ink, 0.45f), 0, 0);
        Block(new Rect(0, 0, Screen.width, Screen.height));
