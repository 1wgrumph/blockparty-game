    // Newest active feeling explained through ResidentPanel.TryExplain; with no feeling,
    // the newest Chat or FriendlyActivity the resident took part in (both name a real world event).
    static string WhyLine(Frame f, ResidentRecord resident)
    {
        Feeling newest = null;
        foreach (Feeling feeling in resident.Feelings)
            if (f.World.GameSeconds < feeling.ExpiryGameSeconds && (newest == null || (long)feeling.SourceEvent >= (long)newest.SourceEvent))
                newest = feeling;
        if (newest != null)
        {
            string head = "Why: " + newest.Kind + " · " + NameOf(f, newest.Other);
            MemoryEntry memory;
            string reason;
            if (f.Panel != null && f.Panel.TryExplain(resident.Id, newest.SourceEvent, out memory, out reason))
                return head + ": " + memory.Kind + " (" + memory.OutcomeCode + ") " + WhenText(memory.GameSeconds);
            return head;
        }
        IReadOnlyList<WorldEvent> events = f.World.Events;
        string listener = "=" + ((long)resident.Id).ToString(CultureInfo.InvariantCulture);
        for (int i = events.Count - 1; i >= 0 && i >= events.Count - 400; i--)
        {
            WorldEvent e = events[i];
            bool chat = e.Kind == "chat";
            if ((!chat && e.Kind != "friendly") || !e.Actor.HasValue) continue;
            bool spoke = e.Actor.Value == resident.Id;
            if (!spoke && !e.Detail.EndsWith(listener, StringComparison.Ordinal)) continue;
            long other = 0L;
            if (spoke && !long.TryParse(e.Detail.Substring(e.Detail.LastIndexOf('=') + 1), out other)) continue;
            ResidentId partner = spoke ? (ResidentId)other : e.Actor.Value;
            return (chat ? "Last: chatted with " : "Last: spent time with ") + NameOf(f, partner) + " · " + WhenText(e.GameSeconds);
        }
        return "Why: no strong feelings yet";
    }

    static string NameOf(Frame f, ResidentId id)
    {
        ResidentRecord r;
        return f.World.TryGetResident(id, out r) ? r.DisplayName : "someone";
    }

    static string Signed(float v) { return (v > 0f ? "+" : "") + Mathf.RoundToInt(v).ToString(CultureInfo.InvariantCulture); }

    static string WhenText(long seconds)
    {
        long day = seconds / Clockwork.GameSecondsPerGameDay, ofDay = seconds % Clockwork.GameSecondsPerGameDay;
        return "Day " + (day + 1) + " " + (ofDay / 3600).ToString("00", CultureInfo.InvariantCulture) + ":"
            + (ofDay % 3600 / 60).ToString("00", CultureInfo.InvariantCulture);
    }

    void Bar(Rect track, float fraction, string fill)
    {
