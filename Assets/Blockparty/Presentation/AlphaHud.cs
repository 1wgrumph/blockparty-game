    // Same nearest-site rule as GymTrailDirector's panel.
    static string Nearest(Frame f, GymTrailDirector trail)
    {
        Vector3 p = GymTrailDirector.V(f.Executor.GetResidentPosition(trail.Resident));
        GymTrailDirector.Place best = trail.Layout.sites[0];
        foreach (GymTrailDirector.Place s in trail.Layout.sites)
            if (Vector3.Distance(p, GymTrailDirector.V(GymTrailDirector.P(s.entry))) < Vector3.Distance(p, GymTrailDirector.V(GymTrailDirector.P(best.entry))))
                best = s;
        return best.id;
    }

