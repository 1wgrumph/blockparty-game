        if (Hit(hit, "Close (" + Key(f, "CloseActionMenu") + ")")) ToggleHistory(f);
        float y = card.y + U(16) + U(44);
        if (history.Count == 0)
        {
            FitText(new Rect(card.x + U(22), y, w - U(44), rowH), "No notices yet", 15, Denim, false, TextAnchor.MiddleLeft);
            return;
        }
        foreach (string[] entry in history)
        {
            Rect row = new Rect(card.x + U(18), y, w - U(36), rowH);
            Panel("opt", row, false);
            Rect mark = new Rect(row.x + U(10), row.center.y - U(8), U(16), U(16));
            bool good = entry[2] == "1";
            if (good) DrawIcon(mark, Icon.Check, Teal);
            else { DrawIcon(mark, Icon.Disc, Rust); Text(mark, "!", 11, White, true, TextAnchor.MiddleCenter); }
            float tw = Measure("12:00 PM", 13, false) + U(6);
            Text(new Rect(row.x + U(34), row.y, tw, rowH), entry[0], 13, OliveDark, false);
            Rect textRect = new Rect(row.x + U(34) + tw + U(4), row.y, row.width - U(48) - tw, rowH);
            FitText(textRect, entry[1], 14, good ? TealDark : RustDark, true, TextAnchor.MiddleLeft);
            if (Hover(row)) tooltip = entry[1];
            y += rowH + U(4);
        }
    }

