    GUIStyle Style(float size, Color color, bool bold, TextAnchor anchor)
    {
        label.fontSize = Mathf.Max(8, Mathf.RoundToInt(size * kf));
        label.fontStyle = bold ? FontStyle.Bold : FontStyle.Normal;
        label.alignment = anchor;
        label.normal.textColor = color;
        return label;
    }

    void Text(Rect r, string s, float size, Color color, bool bold = true, TextAnchor anchor = TextAnchor.MiddleLeft)
    {
        GUI.Label(r, s, Style(size, color, bold, anchor));
    }

    float Measure(string s, float size, bool bold = true)
    {
        return Style(size, Ink, bold, TextAnchor.MiddleLeft).CalcSize(new GUIContent(s)).x;
    }

    // Text shrunk (down to 70%) to fit a width, then clipped.
    void FitText(Rect r, string s, float size, Color color, bool bold, TextAnchor anchor)
    {
        float scale = 1f;
        while (scale > 0.7f && Measure(s, size * scale, bold) > r.width) scale -= 0.05f;
        Text(r, s, size * scale, color, bold, anchor);
    }

