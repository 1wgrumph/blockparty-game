    // "Party 7:00 PM · Cara ✓ · Dev ✗" for a host's open plan; null when none.
    static string PartyLine(Frame f, ResidentId host)
    {
        PartyPlan plan = f.Live.Game.Party.OpenPlan(host);
        if (plan == null) return null;
        var parts = new List<string> { (plan.Announced ? "Party now" : "Party " + Clock12(plan.Start)) };
        foreach (PartyInvite invite in plan.Invites)
        {
            ResidentRecord guest;
            string name = f.World.TryGetResident((ResidentId)invite.Guest, out guest) ? guest.DisplayName : "?";
            parts.Add(name + (invite.Arrived ? " here" : invite.Accepted ? " yes" : " no"));
        }
        return string.Join(" · ", parts.ToArray());
    }

