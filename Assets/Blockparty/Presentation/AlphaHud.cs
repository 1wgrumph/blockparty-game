        float w = card.width;
        Panel("panel", card);
        float y = card.y + U(32);
        DrawLogo(new Rect(card.x + U(24), y, w - U(48), U(TitleLogoH)));
        string[] labels = { "New Game", "Continue", "Settings" };
        string[] subs = { "Start the default neighborhood", f.ContinueOk ? "Load your saved household" : "No saved game",
            "Text size, sound, colour filter, aging, controls, voice" };
        Icon[] glyphs = { Icon.Play, Icon.Reload, Icon.Gear };
        Color[] badges = { Teal, Denim, Olive };
        TitleAction[] actions = { TitleAction.NewGame, TitleAction.Continue, TitleAction.Settings };
        for (int i = 0; i < 3; i++)
        {
            bool enabled = i != 1 || f.ContinueOk;
            bool on = i == 2 && f.SettingsOpen;
            Rect b = TitleButton(i);
            Color old = GUI.color;
            if (!enabled) GUI.color = A(White, 0.6f);
            Panel(on ? "tileOn" : enabled && f.TitleFocus == i && !f.SettingsOpen ? "optHi" : enabled && Hover(b) ? "optHover" : "opt", b, false);
            Rect badge = new Rect(b.x + U(14), b.center.y - U(21), U(42), U(42));
            DrawIcon(badge, Icon.Disc, on ? White : badges[i]);
            DrawIcon(new Rect(badge.x + U(11), badge.y + U(11), U(20), U(20)), glyphs[i], on ? Teal : White);
            string note = i == 1 && f.ContinueOk ? f.ContinueNote ?? "" : "";
            float nw = note.Length > 0 ? Measure(note, 15) + U(10) : 0f;
