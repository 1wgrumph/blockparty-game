    static string TitleCase(string s)
    {
        if (string.IsNullOrEmpty(s)) return "";
        string lower = s.ToLowerInvariant();
        char[] c = lower.ToCharArray();
        for (int i = 0; i < c.Length; i++) if (i == 0 || c[i - 1] == ' ') c[i] = char.ToUpperInvariant(c[i]);
        return new string(c);
    }

    static string StageName(LifeStage stage) { return stage == LifeStage.YoungAdult ? "Young adult" : stage.ToString(); }

    static string JobDisplayName(string jobId)
    {
        if (string.IsNullOrEmpty(jobId)) return "Unemployed";
        if (string.Equals(jobId, "Barista", StringComparison.Ordinal)) return "Barista";
        if (string.Equals(jobId, "JuniorTechnician", StringComparison.Ordinal)
            || string.Equals(jobId, "Technician", StringComparison.Ordinal)) return "Technician";
        if (string.Equals(jobId, "AIEngineer", StringComparison.Ordinal)) return "AI Engineer";
        return jobId;
    }

    static string Friendly(ActionEntry entry)
    {
        string code = entry.Activity.Code ?? "";
        if (entry.Kind == CommandKind.TravelTo || code.Length == 0) return "Travelling";
        if (code.StartsWith("ACT-FOOD", StringComparison.Ordinal)) return "Eating";
        if (code.StartsWith("ACT-WORK", StringComparison.Ordinal)) return "Working";
        if (code.StartsWith("ACT-EDU", StringComparison.Ordinal)) return "Studying";
        if (code.StartsWith("ACT-REL", StringComparison.Ordinal)) return "Socialising";
        if (code.StartsWith("ACT-PARTY", StringComparison.Ordinal)) return "Partying";
        if (code == "ACT-SPORT-01") return "Working out";
        if (code == "ACT-SPORT-02") return "Playing minigolf";
        if (code == "ACT-SPORT-03") return "Riding a bike";
        if (code.StartsWith("ACT-HEALTH", StringComparison.Ordinal)) return "Resting";
        if (code.StartsWith("ACT-CLUB", StringComparison.Ordinal)) return "At the club";
        if (code.StartsWith("ACT-HOME", StringComparison.Ordinal)) return "Home chores";
        if (code.StartsWith("ACT-CREA", StringComparison.Ordinal)) return "Creating";
        return code;
    }

    static Icon ActivityIcon(ActionEntry entry)
    {
        string code = entry.Activity.Code ?? "";
        if (entry.Kind == CommandKind.TravelTo || code.Length == 0) return Icon.Pin;
        if (code.StartsWith("ACT-FOOD", StringComparison.Ordinal)) return Icon.Food;
        if (code.StartsWith("ACT-WORK", StringComparison.Ordinal)) return Icon.Work;
        if (code.StartsWith("ACT-EDU", StringComparison.Ordinal)) return Icon.Education;
        if (code.StartsWith("ACT-REL", StringComparison.Ordinal)) return Icon.Social;
        if (code.StartsWith("ACT-PARTY", StringComparison.Ordinal)) return Icon.Party;
        if (code == "ACT-SPORT-01") return Icon.Dumbbell;
        if (code == "ACT-SPORT-02") return Icon.Minigolf;
        if (code == "ACT-SPORT-03") return Icon.Outing;
        if (code.StartsWith("ACT-HEALTH", StringComparison.Ordinal)) return Icon.HealthKit;
        if (code.StartsWith("ACT-CLUB", StringComparison.Ordinal)) return Icon.Club;
        if (code.StartsWith("ACT-HOME", StringComparison.Ordinal)) return Icon.Home;
        if (code.StartsWith("ACT-CREA", StringComparison.Ordinal)) return Icon.Creative;
        return Icon.Queue;
    }

