    void DrawIcon(Rect r, Icon icon, Color tint)
    {
        if (atlas == null || Event.current.type != EventType.Repaint) return;
        int i = (int)icon;
        const float cell = 128f, inset = 12f, size = 1024f;
        Rect uv = new Rect(((i % 8) * cell + inset) / size, 1f - ((i / 8) * cell + cell - inset) / size,
            (cell - 2 * inset) / size, (cell - 2 * inset) / size);
        Color old = GUI.color;
        GUI.color = tint * old;
        GUI.DrawTextureWithTexCoords(r, atlas, uv, true);
        GUI.color = old;
    }

