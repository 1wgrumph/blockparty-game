    }

    void DrawWorldTag(Frame f, ResidentRecord resident)
    {
        if (resident == null || f.Camera == null || f.RootOf == null) return;
        Transform root = f.RootOf(resident.Id);
        if (root == null) return;
        Vector3 point = f.Camera.WorldToScreenPoint(root.position + Vector3.up * 2.1f);
        if (point.z <= 0f) return;
        ResidentPanelSnapshot view = snapshot != null ? snapshot.Panel : null;
        string text = resident.DisplayName + (view != null && view.Current != null ? " · " + Friendly(view.Current) : "");
        float w = Measure(text, 16) + U(44), h = U(34);
        Rect r = new Rect(point.x - w / 2f, Screen.height - point.y - h - U(10), w, h);
        if (Event.current.type == EventType.Repaint)
        {
            Matrix4x4 m = GUI.matrix;
            Vector2 tip = new Vector2(r.center.x, r.yMax + U(1));
            GUIUtility.RotateAroundPivot(90f, tip);
            DrawIcon(new Rect(tip.x - U(9), tip.y - U(8), U(16), U(16)), Icon.Play, White);
            GUI.matrix = m;
        }
        Panel("bubble", r, false);
        DrawIcon(new Rect(r.x + U(12), r.center.y - U(7), U(14), U(14)), Icon.Disc, Gold);
        Text(new Rect(r.x + U(32), r.y, w - U(38), h), text, 16, Ink);
    }

