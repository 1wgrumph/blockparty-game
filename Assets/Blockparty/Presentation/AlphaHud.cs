    // One activation path for a row click and the keyboard Confirm on the focused row.
    public void ActivateSetting(Frame f, int i)
    {
        SettingsRecord s = f.Access.Settings;
        bool changed = true;
        if (i == 0) changed = f.Access.TrySetTextScale(s.TextScale == 1f ? 1.5f : 1f);
        else if (i == 1) f.Access.SetReducedMotion(!s.ReducedMotion);
        else if (i == 2) f.Access.SetCaptions(!s.Captions);
