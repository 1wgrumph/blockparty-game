// IMAGE@1: Muse Image content for CREATIVE work items (BP-AI-06/07,
// CONTRACT-BP-05-IMG). Consumes CREATIVE@1 (a completed ACT-CREA-01 WorkItem
// and its recorded inputs), AI-BOUNDARY@1 (typed ImageGeneration request,
// terminal outcomes and decision log) and SAVE@1 (content persisted with the
// work item). Plain C# 9, no engine dependency.
// No network and no credential reach this file: the boundary takes
// provisioning plus hasCredential presence only. The outbound body is the
// BP-SECU-02 purpose minimum: model, prompt (personality summary plus the work
// item's one factual memory), n, size, response_format and output_format.
// No other resident data is read into it.
// Success attaches the returned b64 image to the existing work item; denial,
// unavailability, no key, timeout or an unusable frame attaches the disclosed
// pre-authored variant and never records Applied. Delivery is keyed by
// request id, so duplicates and late frames cannot replace content twice.
// JSON: Unity's Assembly-CSharp has no System.Text.Json, so frames parse
// through SaveV1's strict reader (the SAM pattern).
// Fast Enter Play Mode: no static mutable state, no wall-clock reads; real
// time enters only through Tick from the caller.
using System;
using System.Collections.Generic;
using System.Text;
using Blockparty.Activities;
using Blockparty.Contracts;
using Blockparty.Persistence;
using Blockparty.Simulation;

namespace Blockparty.AI
{
    // CONTRACT-BP-05-IMG content for one existing WorkItem: the recorded path
    // (generated or local-alternative), the image bytes and the player-visible
    // disclosure naming which path was used.
    public sealed class ImageContent
    {
        public readonly ObjectId Item;
        public readonly string Path;
        public readonly string ImageBase64;
        public readonly string Disclosure;

        internal ImageContent(ObjectId item, string path, string imageBase64, string disclosure)
        {
            Item = item;
            Path = path;
            ImageBase64 = imageBase64;
            Disclosure = disclosure;
        }
    }

    // Save capture bundle: one row per WorkItem that has content. Rows carry
    // raw item ids; the creative section restores those items first, and
    // Import binds every row to one of them.
    public sealed class ImageSnapshot
    {
        public sealed class Row
        {
            public long Item;
            public string Path;
            public string ImageBase64;
            public string Disclosure;
        }

        public readonly List<Row> Rows = new List<Row>();
    }

    public sealed class ImageAdapter
    {
        private const string GeneratedPath = "generated";
        private const string LocalPath = "local-alternative";
        private const string GeneratedDisclosure = "Generated by Muse Image (muse-image-1.0).";
        // One pre-authored variant ships with this package; the same recorded
        // inputs therefore always select it.
        private const string LocalDisclosure =
            "Local pre-authored variant local-1 used because image generation was unavailable.";
        // 16x16 authored variant; evidence/production/IMAGE/fixtures/local-variant.png
        // is the same bytes. No image file I/O at runtime.
        private const string LocalVariantBase64 =
            "iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAIAAACQkWg2AAAAPUlEQVR42mNQMgkiCTEMkIZrC7yAiFgNENW49DDgUY1VDwN+1Zh6GAiqRtNDgQaSnUSOp8kJVnIibqATHwDRC+mhFQWKFgAAAABJRU5ErkJggg==";

        private readonly WorldState world;
        private readonly ProposalBoundary boundary;
        private readonly Creative creative;
        private readonly Dictionary<GatewayRequestId, ObjectId> pending =
            new Dictionary<GatewayRequestId, ObjectId>();
        private readonly Dictionary<ObjectId, ImageContent> contents =
            new Dictionary<ObjectId, ImageContent>();
        private string payload = string.Empty;

        public ImageAdapter(WorldState world, ProposalBoundary boundary, Creative creative)
        {
            if (world == null) throw new ArgumentNullException("world");
            if (boundary == null) throw new ArgumentNullException("boundary");
            if (creative == null) throw new ArgumentNullException("creative");
            this.world = world;
            this.boundary = boundary;
            this.creative = creative;
        }

        // Outbound JSON body for the last issued request. Empty until a send.
        public string Payload { get { return payload; } }

        public ImageContent GetContent(ObjectId item)
        {
            ImageContent found;
            return contents.TryGetValue(item, out found) ? found : null;
        }

        // Issues one ImageGeneration request for an existing WorkItem. A refused
        // send takes the local alternative at once; a non-WorkItem is ignored.
        public GatewayRequest Request(ObjectId item, ServiceEndpoint endpoint,
            bool hasCredential, bool disclosureGiven)
        {
            if (endpoint == null) throw new ArgumentNullException("endpoint");
            WorkItem work = FindWork(item);
            if (work == null) return null;
            GatewayRequest request = boundary.RequestService(null, GatewayPurpose.ImageGeneration,
                endpoint, hasCredential, disclosureGiven,
                LiveWire.ImageGenerationTimeoutRealSeconds);
            if (request == null)
            {
                SetLocal(item);
                return null;
            }
            payload = BuildPayload(endpoint.ModelId, Prompt(work.Reference));
            pending[request.Id] = item;
            return request;
        }

        // CRAFTS@1: one ImageGeneration request for a craft piece with the
        // caller's prompt (craft kind, trait words, held memory). The item need
        // not be a WorkItem; this adapter instance is never saved, so Import's
        // WorkItem binding still holds for saved content.
        public GatewayRequest RequestPrompt(ObjectId item, string prompt, ServiceEndpoint endpoint,
            bool hasCredential, bool disclosureGiven)
        {
            if (endpoint == null) throw new ArgumentNullException("endpoint");
            if (string.IsNullOrEmpty(prompt)) throw new ArgumentException("Prompt required", "prompt");
            GatewayRequest request = boundary.RequestService(null, GatewayPurpose.ImageGeneration,
                endpoint, hasCredential, disclosureGiven,
                LiveWire.ImageGenerationTimeoutRealSeconds);
            if (request == null)
            {
                SetLocal(item);
                return null;
            }
            payload = BuildPayload(endpoint.ModelId, prompt);
            pending[request.Id] = item;
            return request;
        }

        // Delivers one images-response frame. An already finalized id is an
        // idempotent no-op, so late or duplicate frames never replace content.
        public ProposalVerdict Complete(GatewayRequestId request, string imagesResponse)
        {
            ObjectId item;
            if (!pending.TryGetValue(request, out item)) return ProposalVerdict.DuplicateIgnored;
            pending.Remove(request);
            string image;
            if (!TryParseImage(imagesResponse, out image))
            {
                SetLocal(item);
                return boundary.CompleteService(request, false, "BadFrame");
            }
            ProposalVerdict verdict = boundary.CompleteService(request, true, null);
            if (verdict != ProposalVerdict.Applied)
            {
                SetLocal(item);
                return verdict;
            }
            SetGenerated(item, image);
            return verdict;
        }

        // Provider failure is terminal: the boundary records the outcome and the
        // item keeps the disclosed local alternative.
        public ProposalVerdict Fail(GatewayRequestId request, GatewayOutcome outcome)
        {
            ObjectId item;
            if (!pending.TryGetValue(request, out item))
            {
                return boundary.CompleteFailure(request, outcome);
            }
            pending.Remove(request);
            ProposalVerdict verdict = boundary.CompleteFailure(request, outcome);
            SetLocal(item);
            return verdict;
        }

        // Real-time input for the shared boundary deadline.
        public void Tick(double elapsedRealSeconds)
        {
            boundary.AdvanceRealSeconds(elapsedRealSeconds);
            boundary.Tick();
            boundary.OnResume();
            SettleExpiredPending();
        }

        // The sitting pump advances the shared clock once, then asks this
        // adapter to take its fallback without advancing that clock again.
        internal void SettleExpiredPending()
        {
            if (pending.Count == 0) return;
            List<GatewayRequestId> ids = new List<GatewayRequestId>(pending.Keys);
            for (int i = 0; i < ids.Count; i++)
            {
                ObjectId item;
                if (!pending.TryGetValue(ids[i], out item) || boundary.IsPending(ids[i])) continue;
                pending.Remove(ids[i]);
                SetLocal(item);
            }
        }

        public ImageSnapshot Export()
        {
            ImageSnapshot snapshot = new ImageSnapshot();
            List<ObjectId> ids = new List<ObjectId>(contents.Keys);
            for (int i = 1; i < ids.Count; i++)
            {
                ObjectId key = ids[i];
                int j = i - 1;
                while (j >= 0 && (long)ids[j] > (long)key)
                {
                    ids[j + 1] = ids[j];
                    j--;
                }
                ids[j + 1] = key;
            }
            for (int i = 0; i < ids.Count; i++)
            {
                ImageContent content = contents[ids[i]];
                ImageSnapshot.Row row = new ImageSnapshot.Row();
                row.Item = (long)content.Item;
                row.Path = content.Path;
                row.ImageBase64 = content.ImageBase64;
                row.Disclosure = content.Disclosure;
                snapshot.Rows.Add(row);
            }
            return snapshot;
        }

        // Restores content only for WorkItems the creative section rebuilt.
        // A row that contradicts the work item set, carries an unknown path or
        // undecodable image, or disguises the path it discloses is refused.
        public void Import(StateWriter writer, ImageSnapshot snapshot)
        {
            CheckWriter(writer);
            if (snapshot == null) throw new ArgumentNullException("snapshot");
            if (snapshot.Rows == null)
            {
                throw new ArgumentException("Image bundle rows must exist", "snapshot");
            }
            Dictionary<ObjectId, ImageContent> next =
                new Dictionary<ObjectId, ImageContent>();
            for (int i = 0; i < snapshot.Rows.Count; i++)
            {
                ImageSnapshot.Row row = snapshot.Rows[i];
                if (row == null || row.Path == null || row.ImageBase64 == null
                    || row.Disclosure == null)
                {
                    throw new ArgumentException("Null image content row " + i.ToString(), "snapshot");
                }
                ObjectId item = (ObjectId)row.Item;
                if (FindWork(item) == null)
                {
                    throw new ArgumentException("Image content " + row.Item.ToString()
                        + " is not a creative work item", "snapshot");
                }
                if (!IsKnownPath(row.Path))
                {
                    throw new ArgumentException("Image content " + row.Item.ToString()
                        + " has an unknown path", "snapshot");
                }
                if (!IsPng(row.ImageBase64))
                {
                    throw new ArgumentException("Image content " + row.Item.ToString()
                        + " is not a PNG", "snapshot");
                }
                if (row.Path == LocalPath && !DisclosesLocal(row.Disclosure))
                {
                    throw new ArgumentException("Image content " + row.Item.ToString()
                        + " does not disclose its local path", "snapshot");
                }
                if (row.Path == GeneratedPath
                    && row.Disclosure.IndexOf("generated", StringComparison.OrdinalIgnoreCase) < 0)
                {
                    throw new ArgumentException("Image content " + row.Item.ToString()
                        + " does not disclose its generated path", "snapshot");
                }
                if (next.ContainsKey(item))
                {
                    throw new ArgumentException("Duplicate image content for item "
                        + row.Item.ToString(), "snapshot");
                }
                next[item] = new ImageContent(item, row.Path, row.ImageBase64, row.Disclosure);
            }
            contents.Clear();
            foreach (KeyValuePair<ObjectId, ImageContent> pair in next)
            {
                contents[pair.Key] = pair.Value;
            }
        }

        internal bool HasSaveState()
        {
            return contents.Count != 0;
        }

        private WorkItem FindWork(ObjectId item)
        {
            IReadOnlyList<WorkItem> works = creative.WorkItems;
            for (int i = 0; i < works.Count; i++)
            {
                if (works[i].Reference.Item == item) return works[i];
            }
            return null;
        }

        private string BuildPayload(string modelId, string prompt)
        {
            JsonObject body = new JsonObject();
            body.Add("model", modelId);
            body.Add("prompt", prompt);
            body.Add("n", 1);
            body.Add("size", "1024x1024");
            body.Add("response_format", "b64_json");
            body.Add("output_format", "png");
            StringBuilder sb = new StringBuilder();
            body.Render(sb);
            return sb.ToString();
        }

        // The BP-SEC-07 image purpose: the WorkItem's personality summary plus
        // the one factual memory it recorded. Nothing else is read.
        private string Prompt(WorkItemRef reference)
        {
            return "A wall artwork inspired by a recorded memory: " + MemoryText(reference.MemoryEvent)
                + ". Personality: " + reference.PersonalitySummary + ".";
        }

        private string MemoryText(EventId memory)
        {
            IReadOnlyList<WorldEvent> events = world.Events;
            for (int i = 0; i < events.Count; i++)
            {
                if (events[i].Event == memory) return events[i].Detail;
            }
            return string.Empty;
        }

        private bool TryParseImage(string frame, out string imageBase64)
        {
            imageBase64 = null;
            if (string.IsNullOrEmpty(frame)) return false;
            try
            {
                JsonObject root = JsonParser.ParseSamFrame(frame) as JsonObject;
                if (root == null) return false;
                JsonArray data = root.GetArray("data", "image");
                if (data.Count == 0) return false;
                string found = data.GetObject(0, "image.data").GetString("b64_json", "image.data");
                if (!IsPng(found)) return false;
                imageBase64 = found;
                return true;
            }
            catch (JsonSaveException) { return false; }
        }

        private void SetGenerated(ObjectId item, string imageBase64)
        {
            contents[item] = new ImageContent(item, GeneratedPath, imageBase64, GeneratedDisclosure);
        }

        private void SetLocal(ObjectId item)
        {
            contents[item] = new ImageContent(item, LocalPath, LocalVariantBase64, LocalDisclosure);
        }

        private static bool IsKnownPath(string path)
        {
            return string.Equals(path, GeneratedPath, StringComparison.Ordinal)
                || string.Equals(path, LocalPath, StringComparison.Ordinal);
        }

        private static bool DisclosesLocal(string text)
        {
            return !string.IsNullOrWhiteSpace(text)
                && (text.IndexOf("local", StringComparison.OrdinalIgnoreCase) >= 0
                    || text.IndexOf("pre-authored", StringComparison.OrdinalIgnoreCase) >= 0);
        }

        private static bool IsPng(string base64)
        {
            if (string.IsNullOrEmpty(base64)) return false;
            try
            {
                byte[] bytes = Convert.FromBase64String(base64);
                return bytes.Length > 8
                    && bytes[0] == 137 && bytes[1] == 80 && bytes[2] == 78 && bytes[3] == 71
                    && bytes[4] == 13 && bytes[5] == 10 && bytes[6] == 26 && bytes[7] == 10;
            }
            catch (FormatException) { return false; }
        }

        private static void CheckWriter(StateWriter writer)
        {
            if (writer != StateWriter.SimCore && writer != StateWriter.CommandArbitrator
                && writer != StateWriter.ActivityExecutor)
            {
                throw new ArgumentException("Unknown state writer", "writer");
            }
        }
    }
}
